function interpret(score, hi, mid, labels) {
  if (score == null) return "недостаточно данных";
  if (score >= hi) return labels[0];
  if (score >= mid) return labels[1];
  return labels[2];
}

export function scoreTemperament(gender, answers) {
  const questions = gender === "f" ? femaleQuestions : maleQuestions;
  const blocks = {};
  for (const [key, qs] of Object.entries(questions)) {
    const vals = qs.map((q) => Number(answers[q.id])).filter((v) => v > 0);
    blocks[key] = vals.length ? Math.round((vals.reduce((a, b) => a + b, 0) / vals.length) * 100) / 100 : null;
  }
  const b1 = blocks.block1, b2 = blocks.block2, b3 = blocks.block3, b4 = blocks.block4;
  const female = gender === "f";
  let typeName = "Смешанный профиль";
  let typeDesc = "Сверьте с конституцией бланка и жалобой. Не все оси обязаны совпасть.";
  if (b1 != null && b2 != null && b3 != null) {
    if (b1 >= 3.5 && b2 >= 3.2 && b3 <= 2.2) {
      typeName = female ? "Огненный темперамент" : "Высокий природный потенциал";
      typeDesc = female
        ? "Мощная база, быстрое возбуждение, низкая чувствительность к помехам. Разрядка — базовая потребность. Экологичные каналы, а не стыд."
        : "Быстрая возбудимость, стрессоустойчивость в сексе. Разрядка скорее гигиена. Реже невроз «из-за секса».";
    } else if (b2 >= 3.2 && b3 >= 3.2) {
      typeName = "Конфликтный: драйв + торможение";
      typeDesc = "Хочет, но стыд, контроль, обстановка или страх неудачи гасят. Частая мишень секстерапии (фокусирование, сценарии, пара). Совпадает с Dual Control: высокий SES при высоком SIS1.";
    } else if ((b1 ?? 3) <= 2.5 && b3 >= 3.2) {
      typeName = "Чувствительный / тормозимый";
      typeDesc = "Помехи сильнее драйва. Не стыдить за «слабое либидо». Сначала безопасность, контекст, SIS2 (последствия) и SIS1 (ожидание неудачи).";
    } else if ((b1 ?? 3) <= 2.5 && b2 <= 2.2) {
      typeName = "Рецептивный тип";
      typeDesc = "Желание отзывчивое, не спонтанное. Нужны время, атмосфера, касание. Не путать с дисфункцией.";
    }
  }
  return {
    blocks,
    bio: interpret(b1, 3.5, 2.5, ["Сильная", "Средняя", "Слабая"]),
    drive: interpret(b2, 3.2, 2.2, ["Высокий драйв", "Умеренный драйв", "Низкий спонтанный драйв (рецептивный)"]),
    inhib: interpret(b3, 3.2, 2.2, ["Высокое торможение", "Умеренное торможение", "Низкое торможение"]),
    abst: interpret(b4, 3.2, 2.2, ["Тяжёлая абстиненция", "Умеренный дискомфорт", "Лёгкая переносимость"]),
    typeName,
    typeDesc,
  };
}

