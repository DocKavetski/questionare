export function comorbidCodes(state) {
  const on = (id) => !!state.checks["cm:" + id];
  const codes = [];
  const mainDep = ["dep_main_1", "dep_main_2", "dep_main_3"].filter(on).length;
  const addDep = ["dep_add_1", "dep_add_2", "dep_add_3", "dep_add_4", "dep_add_5", "dep_add_6"].filter(on).length;
  const totalDep = mainDep + addDep;
  const hasPsychotic = on("dep_severe_1");
  const hasSuicidal = on("dep_severe_3");
  const selfcareLoss = on("dep_severe_4");
  let depCode = "";
  if (mainDep >= 2) {
    if (hasPsychotic || hasSuicidal || selfcareLoss) depCode = "F32.3";
    else if ((mainDep === 3 && addDep >= 4) || totalDep >= 7) depCode = "F32.2";
    else if ((mainDep >= 2 && addDep >= 3 && totalDep >= 5) || (mainDep === 3 && addDep >= 2 && totalDep >= 5)) depCode = "F32.1";
    else depCode = "F32.0";
  }
  if (on("recur_2")) depCode = "F34.1";
  else if (on("recur_1") && depCode.startsWith("F32")) depCode = depCode.replace("F32", "F33");
  if (depCode) codes.push(depCode);
  const gad = ["anx_gad_1", "anx_gad_2", "anx_gad_3", "anx_gad_4", "anx_gad_5", "anx_gad_6"].filter(on).length;
  if (gad >= 3) codes.push("F41.1");
  if (on("anx_panic_1")) codes.push("F41.0");
  if (on("anx_panic_2")) codes.push("F40.0");
  if (on("ocd_1") || on("ocd_2")) codes.push("F42");
  if (on("somatic_1") || on("somatic_2")) codes.push("F45");
  if (on("stress_1") || on("stress_2")) codes.push(on("stress_3") ? "F43.22" : "F43.2");
  else if (on("stress_3")) codes.push("F43.22");
  if (on("other_1")) codes.push("F43.1");
  if (on("other_2")) codes.push("F44");
  return [...new Set(codes)];
}

