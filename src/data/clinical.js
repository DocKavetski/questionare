export function redFlags(state) {
  const female = state.patient.sex === "f";
  const chk = (id) => !!state.checks[id];
  const f = (id) => state.fields[id] || "";
  const selected = (prefix, opts) => opts.filter((o) => chk(prefix + ":" + o));
  const out = [];
  if (chk("sui:мысли") || chk("sui:замысел") || chk("sui:намерение") || f("sui_note") || chk("cm:dep_severe_3")) {
    out.push("суицидальный риск");
  }
  if (!female && selected("erect_gone", ["при попытке совершить пенетрацию", "во время первых фрикций"]).length) {
    out.push("ситуационная ЭД");
  }
  if (female && (selected("lub_coitus", ["исчезает", "отсутствует"]).length || selected("pen_why", ["боль", "судорожный спазм мышц"]).length || chk("sdx:vag"))) {
    out.push("боль/спазм/любрикация");
  }
  if (chk("sdx:s1") || /сиозс|сертралин|пароксетин|флуокс|эсцитал|венлафакс|тразодон|амитрипт|антидепресс|кок/i.test(f("meds") + f("iv_meds"))) {
    out.push("лекарственный фактор (АД/препараты)");
  }
  return out;
}

