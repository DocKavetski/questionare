export default function Handouts({ extra, go }) {
  const [cat, setCat] = useState("все");
  const cats = ["все", ...new Set(HANDOUTS.map((h) => h.cat))];
  const list = HANDOUTS.filter((h) => cat === "все" || h.cat === cat);
  const meta = HANDOUTS.find((h) => h.id === extra);

  if (extra) {
    return (
      <>
        <Sheet title={meta?.title || ""}>
          <HandoutBody id={extra} />
        </Sheet>
        <p className="no-print" style={{ marginTop: 12 }}>
          <button className="btn" type="button" onClick={() => window.print()}>Печать</button>
          <button className="btn ghost" type="button" onClick={() => go("handouts")} style={{ marginLeft: 8 }}>К каталогу</button>
        </p>
      </>
    );
  }

  return (
    <>
      <h1>Раздатки и памятки АД</h1>
      <p className="lede">ФИО из шапки попадёт в печатный лист. PDF открываются в новой вкладке, если файлы есть в репозитории.</p>
      <div className="filters">
        {cats.map((c) => (
          <button key={c} type="button" className={"filter" + (c === cat ? " on" : "")} onClick={() => setCat(c)}>{c}</button>
        ))}
      </div>
      <div className="grid cards">
        {list.map((h) => (
          <div key={h.id} className="card click" onClick={() => go("handout/" + h.id)}>
            <span className="tag">{h.cat}</span>
            <h3>{h.title}</h3>
            <p>{h.sub}</p>
          </div>
        ))}
      </div>
    </>
  );
}
